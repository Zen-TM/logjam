// Regenerates src/gaugeDropSdf.ts: the water drop marking a river gauge on the
// map. Run with `node scripts/generate-gauge-drop-sdf.mjs`. An SDF for the
// reasons in generate-route-arrow-sdf.mjs, and so its ring is the map's own
// halo rather than a second colour baked in.
import { writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { EDGE_ALPHA, SPREAD_PX, sdfPng } from "./sdfPng.mjs";

const SIZE = 64;
const CENTRE_X = SIZE / 2;
const CENTRE_Y = 40;
const RADIUS = 15;
const TIP_Y = 10;
const ARC_POINTS = 48;

// The tip, then the circle from one tangent to the other, round the bottom.
const tangent = Math.acos(RADIUS / (CENTRE_Y - TIP_Y));
const arc = Array.from({ length: ARC_POINTS + 1 }, (_, i) => {
  const a = tangent + (i / ARC_POINTS) * (2 * Math.PI - 2 * tangent);
  return [CENTRE_X + RADIUS * Math.sin(a), CENTRE_Y - RADIUS * Math.cos(a)];
});
const png = sdfPng(SIZE, SIZE, [[CENTRE_X, TIP_Y], ...arc]);

const out = join(
  dirname(fileURLToPath(import.meta.url)),
  "../src/gaugeDropSdf.ts",
);
writeFileSync(
  out,
  `// GENERATED by scripts/generate-gauge-drop-sdf.mjs — do not edit by hand.
//
// ${SIZE}x${SIZE} SDF, distance in the alpha channel with the shape edge at alpha
// ${Math.round(EDGE_ALPHA * 255)} and a ${SPREAD_PX}px spread.
export const GAUGE_ICON_SDF_URI =
  "data:image/png;base64,${png.toString("base64")}";
`,
  "utf8",
);
