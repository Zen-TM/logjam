// Regenerates src/placeBadgeImages.ts: the status badge on a place pin, a
// filled disc with a white person (shared) or tick (visited) and a white rim.
// Run with `node scripts/generate-place-badge-images.mjs`. Plain bitmaps, not
// SDFs: an SDF is one colour, and a badge is two plus a rim. The disc colours
// repeat SHARED_PLACE_COLOR / VISITED_PLACE_COLOR; placeBadge.test.ts fails if
// they drift.
import { writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { rgbaPng } from "./sdfPng.mjs";

const SIZE = 128;
const C = SIZE / 2;
const RIM_R = 60;
const DISC_R = 52;
const SUPER = 4;

const dist = (x, y, [ax, ay], [bx, by]) => {
  const dx = bx - ax;
  const dy = by - ay;
  const t = Math.max(
    0,
    Math.min(1, ((x - ax) * dx + (y - ay) * dy) / (dx * dx + dy * dy)),
  );
  return Math.hypot(x - ax - t * dx, y - ay - t * dy);
};

const person = (x, y) =>
  Math.hypot(x - C, y - 50) <= 12 ||
  (y >= 64 && y <= 88 && ((x - C) / 26) ** 2 + ((y - 88) / 24) ** 2 <= 1);
const tick = (x, y) =>
  dist(x, y, [40, 66], [57, 82]) <= 6.5 ||
  dist(x, y, [57, 82], [90, 46]) <= 6.5;

const badges = {
  SHARED: ["#B79EC0", person],
  VISITED: ["#2F9E6B", tick],
};

const hex = (h) => [1, 3, 5].map((i) => parseInt(h.slice(i, i + 2), 16));

function render(colour, glyph) {
  const rgba = Buffer.alloc(SIZE * SIZE * 4);
  const fill = hex(colour);
  for (let py = 0; py < SIZE; py++) {
    for (let px = 0; px < SIZE; px++) {
      let r = 0,
        g = 0,
        b = 0,
        a = 0;
      for (let sy = 0; sy < SUPER; sy++) {
        for (let sx = 0; sx < SUPER; sx++) {
          const x = px + (sx + 0.5) / SUPER;
          const y = py + (sy + 0.5) / SUPER;
          const d = Math.hypot(x - C, y - C);
          if (d > RIM_R) continue;
          const c = d > DISC_R || glyph(x, y) ? [255, 255, 255] : fill;
          r += c[0];
          g += c[1];
          b += c[2];
          a++;
        }
      }
      const at = (py * SIZE + px) * 4;
      if (a) {
        rgba[at] = Math.round(r / a);
        rgba[at + 1] = Math.round(g / a);
        rgba[at + 2] = Math.round(b / a);
      }
      rgba[at + 3] = Math.round((255 * a) / (SUPER * SUPER));
    }
  }
  return rgbaPng(SIZE, SIZE, rgba).toString("base64");
}

const body = Object.entries(badges)
  .map(
    ([name, [colour, glyph]]) =>
      `export const PLACE_BADGE_${name}_URI =\n  "data:image/png;base64,${render(colour, glyph)}";\n`,
  )
  .join("\n");
writeFileSync(
  join(dirname(fileURLToPath(import.meta.url)), "../src/placeBadgeImages.ts"),
  `// GENERATED by scripts/generate-place-badge-images.mjs — do not edit by hand.
//
// ${SIZE}x${SIZE} bitmaps: a status-coloured disc with a white glyph, inside a
// white rim ${RIM_R - DISC_R}px thick, centred, ${RIM_R * 2}px across.
${body}`,
  "utf8",
);
