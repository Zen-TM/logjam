// Regenerates src/coverageHatchImages.ts: the Coverage overlay's hatch, as a
// `fill-pattern` image. Run with
// `node scripts/generate-coverage-hatch-images.mjs`. Diagonal lines, each a
// dark core edged in light. Drawn at 2x for a sharp line on a high-density
// screen: each client registers it at pixel ratio COVERAGE_HATCH_PIXEL_RATIO.
// nswCoverage.test.ts fails if this drifts.
import { writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { rgbaPng } from "./sdfPng.mjs";

const SIZE = 48;
const SUPER = 4;
// A dark core in MAP_INK.casing with a light edge in MAP_INK.label each side,
// as a casing sets a line off any ground: the dark reads on a light basemap,
// the light on imagery.
const CORE = [0x4e, 0x49, 0x44];
const EDGE = [0xf7, 0xf3, 0xec];
const CORE_WIDTH = 2.5;
const EDGE_WIDTH = 1.5;

// Sparse and faint enough to leave the map readable under it: it covers
// most of the bush.
const HATCH = { spacing: 24, core: 0.35, edge: 0.27 };

function render({ spacing, core, edge }) {
  const rgba = Buffer.alloc(SIZE * SIZE * 4);
  for (let py = 0; py < SIZE; py++) {
    for (let px = 0; px < SIZE; px++) {
      // Premultiplied sums over the subsamples, then back to straight alpha.
      let r = 0,
        g = 0,
        b = 0,
        a = 0;
      for (let sy = 0; sy < SUPER; sy++) {
        for (let sx = 0; sx < SUPER; sx++) {
          // Lines x + y = k * spacing: "/" on screen, and seamless across the
          // tile since spacing divides SIZE.
          const u =
            (px + (sx + 0.5) / SUPER + py + (sy + 0.5) / SUPER) % spacing;
          const d = Math.min(u, spacing - u) / Math.SQRT2;
          const [colour, alpha] =
            d <= CORE_WIDTH / 2
              ? [CORE, core]
              : d <= CORE_WIDTH / 2 + EDGE_WIDTH
                ? [EDGE, edge]
                : [CORE, 0];
          r += colour[0] * alpha;
          g += colour[1] * alpha;
          b += colour[2] * alpha;
          a += alpha;
        }
      }
      const at = (py * SIZE + px) * 4;
      if (a > 0) {
        rgba[at] = Math.round(r / a);
        rgba[at + 1] = Math.round(g / a);
        rgba[at + 2] = Math.round(b / a);
      }
      rgba[at + 3] = Math.round((255 * a) / (SUPER * SUPER));
    }
  }
  return rgbaPng(SIZE, SIZE, rgba).toString("base64");
}

writeFileSync(
  join(
    dirname(fileURLToPath(import.meta.url)),
    "../src/coverageHatchImages.ts",
  ),
  `// GENERATED by scripts/generate-coverage-hatch-images.mjs — do not edit by hand.
//
// ${SIZE}x${SIZE} tiles of diagonal lines: a ${CORE_WIDTH}px core in #4E4944 with a
// ${EDGE_WIDTH}px #F7F3EC edge each side, every ${HATCH.spacing}px.
export const COVERAGE_HATCH_URI =
  "data:image/png;base64,${render(HATCH)}";
`,
  "utf8",
);
