// Regenerates src/windArrowSdf.ts: the arrow the Weather overlay draws for the
// wind, pointing east like the route arrowhead so the same `rotate` turns it.
// Run with `node scripts/generate-wind-arrow-sdf.mjs`. Unlike the route
// arrowhead it has a shaft: a lone triangle on a grid read as noise, and the
// shaft is what says "this way" at a glance. An SDF for the reasons in
// generate-route-arrow-sdf.mjs.
import { writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { EDGE_ALPHA, SPREAD_PX, sdfPng } from "./sdfPng.mjs";

const WIDTH = 64;
const HEIGHT = 32;
const MID = HEIGHT / 2;
const TAIL = SPREAD_PX + 2;
const TIP = WIDTH - SPREAD_PX - 2;
const HEAD = 16;
const HEAD_HALF = 7;
const SHAFT_HALF = 1.5;

const png = sdfPng(WIDTH, HEIGHT, [
  [TAIL, MID - SHAFT_HALF],
  [TIP - HEAD, MID - SHAFT_HALF],
  [TIP - HEAD, MID - HEAD_HALF],
  [TIP, MID],
  [TIP - HEAD, MID + HEAD_HALF],
  [TIP - HEAD, MID + SHAFT_HALF],
  [TAIL, MID + SHAFT_HALF],
]);

const out = join(
  dirname(fileURLToPath(import.meta.url)),
  "../src/windArrowSdf.ts",
);
writeFileSync(
  out,
  `// GENERATED by scripts/generate-wind-arrow-sdf.mjs — do not edit by hand.
//
// ${WIDTH}x${HEIGHT} SDF, an arrow pointing east, distance in the alpha channel
// with the shape edge at alpha ${Math.round(EDGE_ALPHA * 255)} and a ${SPREAD_PX}px spread.
export const WIND_ARROW_SDF_URI =
  "data:image/png;base64,${png.toString("base64")}";
`,
  "utf8",
);
